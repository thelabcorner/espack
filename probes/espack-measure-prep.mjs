#!/usr/bin/env node
// ESPACK measurement driver (temp harness - not part of the repo).
// Measures the two load-bearing unknowns from the handoff on the LIVE engine:
//   1. ESB64.atob decode threshold + timing at 16K/24K/32K/48K/64K, plus
//      chunked full-payload decode (16K/24K/32K chunks).
//   2. File BINARY byte fidelity (all 256 byte values, incl. NULs; small +
//      DLL-size round trips), %LOCALAPPDATA% write + nested-folder create,
//      and a full extraction simulation (decode -> write -> read -> compare).
// Generated probes are stall-safe (file-logged) and run ascending sizes so a
// wedge leaves a trail and stops at the threshold.
