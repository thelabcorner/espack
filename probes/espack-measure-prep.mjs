if (!existsSync(VENDOR.replace(/\//g, '\\'))) { console.error('vendor missing: ' + VENDOR); process.exit(1); }

// deterministic ~99 KB test payload (no external DLL dependency)
var dllBytes = Buffer.alloc(99328);
for (var pi = 0; pi < dllBytes.length; pi++) dllBytes[pi] = (pi * 131 + 17) & 0xff;
var payloadB64 = dllBytes.toString('base64');
console.log('DLL bytes: ' + dllBytes.length + ' -> base64 chars: ' + payloadB64.length);

// ---- deterministic test inputs -------------------------------------------------
// size must be a multiple of 4; byte length = size*3/4 so b64 has no padding.
function pattern(size, variant) {
  var nb = (size / 4) * 3;
  var out = Buffer.alloc(nb);
  for (var i = 0; i < nb; i++) out[i] = (i * 131 + variant * 7 + 17) & 0xff;
  return out.toString('base64');
}

var SIZES = [16384, 24576, 32768, 49152, 65536];
var decInputs = {};
SIZES.forEach(function (s) {
  decInputs[s] = [pattern(s, 1), pattern(s, 2), pattern(s, 3)];
});

// expected window sums + samples for the decoded DLL payload (24K-unit windows)
var WINDOW = 24576;
function windowSums(bytes) {
  var sums = [];
  for (var w = 0; w < bytes.length; w += WINDOW) {
    var sum = 0;
    for (var k = w; k < Math.min(w + WINDOW, bytes.length); k++) sum += bytes[k];
    sums.push(sum);
  }
  return sums;
}
var payloadSums = windowSums(dllBytes);
function samples(bytes) {
  var s = [];
  var picks = [0, 1, 2, 3, 63, 64, 255, 256, 1024, 16384, 32768, 49152, 65536, 98300, 98301, bytes.length - 4, bytes.length - 3, bytes.length - 2, bytes.length - 1];
  for (var i = 0; i < picks.length; i++) {
    var o = picks[i];
    if (o >= 0 && o < bytes.length) s.push([o, bytes[o]]);
  }
  return s;
}
var payloadSamples = samples(dllBytes);
var bigPattern = Buffer.alloc(98304);
for (var i = 0; i < bigPattern.length; i++) bigPattern[i] = i % 256;
var bigSums = windowSums(bigPattern);
var bigSamples = samples(bigPattern);
var smallPattern = Buffer.alloc(512);
for (var j = 0; j < smallPattern.length; j++) smallPattern[j] = j % 256;

function jsStr(s) { // safe single-line JS string literal (b64/text only)
  return '"' + s + '"';
}
function jsNumArr(a) { return '[' + a.join(',') + ']'; }
function jsSampleArr(a) {
  var out = [];
  for (var i = 0; i < a.length; i++) out.push('[' + a[i][0] + ',' + a[i][1] + ']');
  return '[' + out.join(',') + ']';
}

