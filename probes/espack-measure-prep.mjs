// ---- run probe 1 ----------------------------------------------------------------
function runProbe(name) {
  var probePath = join(ROOT, name).replace(/\\/g, '/');
  console.log('--- running ' + name + ' ---');
  var t0 = Date.now();
  var pyOut;
  try {
    pyOut = execFileSync(PY, [TOOL, 'eval', '--file', probePath], { encoding: 'utf8', timeout: 180000 });
  } catch (e) {
    console.error('COM tool failed (possible engine wedge): ' + String((e.stdout || e.message) + '').slice(0, 1500));
    return null;
  }
  var env;
  try { env = JSON.parse(pyOut.trim()); }
  catch (e) { console.error('tool output not JSON: ' + pyOut.slice(0, 500)); return null; }
  if (!env.ok || !env.result || env.result.ok !== true) {
    console.error('tool/engine error: ' + JSON.stringify(env).slice(0, 2000));
    return null;
  }
  var report = env.result.result;
  console.log('wallMs=' + (Date.now() - t0) + ' toolElapsed=' + (env.elapsed !== undefined ? env.elapsed : 'n/a'));
  return report;
}

